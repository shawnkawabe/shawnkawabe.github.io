// Builds src/styles/tokens.css from tokens/*.tokens.json (DTCG 2025.10).
// :root = primitives + dark semantic tokens; [data-theme="light"] = light semantic overrides.
// Two Style Dictionary runs are needed because both theme files define the same token paths.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import StyleDictionary from 'style-dictionary';

const OUTPUT = 'src/styles/tokens.css';
const PREFIX = 'pf-g';
const ROOT_FONT_PX = 16;
const FLUID_FROM_PX = 375;
const FLUID_TO_PX = 1440;

const round = (n) => Number(n.toFixed(4));
const rem = (px) => `${round(px / ROOT_FONT_PX)}rem`;
const dimension = ({ value, unit }) => `${value}${unit}`;

function color({ components, alpha = 1, hex }) {
  if (alpha >= 1 && hex) return hex;
  const [r, g, b] = components.map((c) => Math.round(c * 255));
  return alpha >= 1 ? `rgb(${r} ${g} ${b})` : `rgb(${r} ${g} ${b} / ${alpha})`;
}

// min at 375px viewport, max at 1440px; equal pairs need no fluid term.
function fluid({ min, max }) {
  const minPx = min.value;
  const maxPx = max.value;
  if (minPx === maxPx) return rem(minPx);
  const slope = (maxPx - minPx) / (FLUID_TO_PX - FLUID_FROM_PX);
  const intercept = minPx - slope * FLUID_FROM_PX;
  return `clamp(${rem(minPx)}, ${rem(intercept)} + ${round(slope * 100)}vw, ${rem(maxPx)})`;
}

// Quote only names with spaces: quoting generic families (system-ui, sans-serif) breaks them.
const fontFamily = (families) => families.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');

const shadow = (layers) =>
  layers
    .map((l) =>
      [l.offsetX, l.offsetY, l.blur, l.spread].map(dimension).concat(color(l.color)).join(' '),
    )
    .join(', ');

const VALUE_BY_TYPE = {
  color,
  dimension,
  duration: dimension,
  fontFamily,
  shadow,
  fluidFontSize: fluid,
  cubicBezier: (points) => `cubic-bezier(${points.join(', ')})`,
};

StyleDictionary.registerPreprocessor({
  name: 'pf/fluid-font-size',
  preprocessor: (tokens) => {
    const sizes = tokens.font?.size;
    if (!sizes) return tokens;
    for (const [step, pair] of Object.entries(sizes)) {
      if (step.startsWith('$')) continue;
      sizes[step] = {
        $type: 'fluidFontSize',
        $value: { min: pair.min.$value, max: pair.max.$value },
      };
    }
    return tokens;
  },
});

StyleDictionary.registerTransform({
  name: 'pf/name',
  type: 'name',
  transform: (token) => [PREFIX, ...token.path].join('-'),
});

StyleDictionary.registerTransform({
  name: 'pf/value',
  type: 'value',
  filter: (token) => token.$type in VALUE_BY_TYPE,
  transform: (token) => VALUE_BY_TYPE[token.$type](token.$value),
});

async function buildBlock({ theme, selector, onlyThemeTokens }) {
  const sd = new StyleDictionary({
    // Base is `include` so the theme may override it without collision warnings;
    // the light run outputs only `isSource` (theme) tokens.
    include: ['tokens/base.tokens.json'],
    source: [`tokens/theme.${theme}.tokens.json`],
    preprocessors: ['pf/fluid-font-size'],
    log: { verbosity: 'silent', warnings: 'error' },
    platforms: {
      css: {
        transforms: ['pf/name', 'pf/value'],
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            filter: onlyThemeTokens ? (token) => token.isSource : undefined,
            options: { selector, showFileHeader: false, outputReferences: false },
          },
        ],
      },
    },
  });
  const [file] = await sd.formatPlatform('css');
  return file.output.trim();
}

const blocks = await Promise.all([
  buildBlock({ theme: 'dark', selector: ':root', onlyThemeTokens: false }),
  buildBlock({ theme: 'light', selector: '[data-theme="light"]', onlyThemeTokens: true }),
]);

const header = `/**
 * GENERATED by \`npm run tokens\` from tokens/*.tokens.json. Do not edit.
 * :root = primitives + dark theme; [data-theme="light"] = light theme overrides.
 */`;

await mkdir(dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, `${header}\n${blocks.join('\n\n')}\n`);
console.log(`tokens: wrote ${OUTPUT}`);

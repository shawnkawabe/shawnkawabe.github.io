// Regenerates the site icons in public/ (BACKLOG-LANDING L-45) from one drawing: a round dark badge
// with a white SK, ringed by a thin accent orbit that carries one accent moon, after the hero globe
// and its cloud moons. Colours come from the dark theme in src/styles/tokens.css, so re-run
// `npm run icons` after changing surface-0, on-surface-1 or accent-1.
// Writes favicon.svg, favicon.ico (16, 32 and 48px PNG frames), apple-touch-icon.png, the
// manifest icons and site.webmanifest.
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const tokens = readFileSync('src/styles/tokens.css', 'utf8');
/** First (dark theme) value of a colour token. */
const token = (name) => tokens.match(new RegExp(`--pf-g-color-${name}: (#[0-9A-Fa-f]{6});`))[1];
const surface = token('surface-0');
const accent = token('accent-1');
const ink = token('on-surface-1');

// On a 32 grid around the centre. S is two half rings joined by a spine, K three bars; butt caps
// keep the ends square. The moon sits on the orbit at 45°, cut out of it by a surface-coloured rim.
const mark = `<circle cx="16" cy="16" r="13.4" fill="none" stroke="${accent}" stroke-opacity="0.6" stroke-width="1.6" />
  <circle cx="25.5" cy="6.5" r="2.9" fill="${accent}" stroke="${surface}" stroke-width="1.4" />
  <g transform="translate(16 16) scale(0.76) translate(-16.1 -16)" fill="none" stroke="${ink}" stroke-width="3.8">
    <path d="M15.4 10H10.2a3 3 0 0 0 0 6h2.2a3 3 0 0 1 0 6H5.6" />
    <path d="M19.6 8.1v15.8M26.4 8.1l-6.8 7.8M22.2 13.4l4.6 10.5" />
  </g>`;

/** The tab icon: the badge on transparent corners. */
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <!-- Generated by scripts/icons.mjs (BACKLOG-LANDING L-45); edit the script, not this file. -->
  <circle cx="16" cy="16" r="16" fill="${surface}" />
  ${mark}
</svg>
`;

/** Full bleed, for platforms that cut their own shape; `scale` keeps the mark in the safe zone. */
const fullBleed = (scale) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" fill="${surface}" />
  <g transform="translate(16 16) scale(${scale}) translate(-16 -16)">${mark}</g>
</svg>`;

const browser = await chromium.launch();
const page = await browser.newPage();
async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  const src = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  await page.setContent(
    `<style>body{margin:0}img{display:block}</style><img src="${src}" width="${size}" height="${size}">`,
  );
  return page.screenshot({ omitBackground: true });
}

/** An ICO whose frames are PNGs, which every current browser reads. */
function ico(frames) {
  const header = Buffer.alloc(6 + 16 * frames.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  frames.forEach(({ size, data }, index) => {
    const entry = 6 + 16 * index;
    header.writeUInt8(size % 256, entry);
    header.writeUInt8(size % 256, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...frames.map(({ data }) => data)]);
}

try {
  const write = (file, data) => {
    writeFileSync(`public/${file}`, data);
    console.log(`icons: public/${file}`);
  };
  write('favicon.svg', favicon);
  const frames = [];
  for (const size of [16, 32, 48]) frames.push({ size, data: await png(favicon, size) });
  write('favicon.ico', ico(frames));
  write('apple-touch-icon.png', await png(fullBleed(0.84), 180));
  write('icon-192.png', await png(favicon, 192));
  write('icon-512.png', await png(favicon, 512));
  // Maskable icons are cropped to a circle as small as 80% of the side; the mark stays inside it.
  write('icon-maskable-512.png', await png(fullBleed(0.72), 512));
  const manifest = {
    name: 'Shawn Kawabe',
    short_name: 'Shawn Kawabe',
    start_url: '/',
    display: 'browser',
    background_color: surface,
    theme_color: surface,
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  };
  write('site.webmanifest', `${JSON.stringify(manifest, null, 2)}\n`);
} finally {
  await browser.close();
}

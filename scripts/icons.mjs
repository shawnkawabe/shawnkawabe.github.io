// Regenerates the site icons from one drawing: the SK Ribbon mark (docs/brand/ICON.md), one
// rounded stroke that draws the S and runs on into the K stem, in accent-1 on a surface-0 squircle.
// Colours come from the dark theme in src/styles/tokens.css, so re-run `npm run icons` after
// changing surface-0 or accent-1.
// Writes favicon.svg, favicon.ico (16, 32 and 48px PNG frames), apple-touch-icon.png, the manifest
// icons and site.webmanifest to public/, and the inline currentColor mark to src/assets/logo-mark.svg.
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const tokens = readFileSync('src/styles/tokens.css', 'utf8');
/** First (dark theme) value of a colour token. */
const token = (name) => tokens.match(new RegExp(`--pf-g-color-${name}: (#[0-9A-Fa-f]{6});`))[1];
const surface = token('surface-0');
const accent = token('accent-1');

// Stroke centre lines on the 32 grid, inside the 6–26 keyline square. Every gap is half a stroke.
const STROKE = 3;
const RIBBON = 'M7.25 21.5H11.75a2.75 2.75 0 0 0 0 -5.5H10a2.75 2.75 0 0 1 0 -5.5H19V21.5';
const ARMS = 'M24.75 10.5L19.5 16L24.75 21.5';
/** At 16 and 32px the same drawing is scaled up so every gap stays at least 1px. */
const SMALL = 1.12;

/** A superellipse tile (n = 5), calmer than a rounded rectangle at large sizes. */
function squircle(n = 5, steps = 96) {
  const points = [];
  for (let i = 0; i < steps; i++) {
    const t = (2 * Math.PI * i) / steps;
    const axis = (v) => (16 + 16 * Math.sign(v) * Math.abs(v) ** (2 / n)).toFixed(2);
    points.push(`${axis(Math.cos(t))} ${axis(Math.sin(t))}`);
  }
  return `M${points.join('L')}Z`;
}
const TILE = squircle();

/** The mark, scaled about the grid centre. */
const mark = (color, scale = 1) => {
  const transform =
    scale === 1 ? '' : ` transform="translate(16 16) scale(${scale}) translate(-16 -16)"`;
  return `<g${transform} fill="none" stroke="${color}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round"><path d="${RIBBON}" /><path d="${ARMS}" /></g>`;
};

/** The tab icon on the squircle tile; `small` is the 16/32px master. */
const tile = (small = false) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <!-- Generated by scripts/icons.mjs (docs/brand/ICON.md); edit the script, not this file. -->
  <path d="${TILE}" fill="${surface}" />
  ${mark(accent, small ? SMALL : 1)}
</svg>
`;

/** Full bleed, for platforms that cut their own shape; `scale` keeps the mark in the safe zone. */
const fullBleed = (scale) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" fill="${surface}" />
  ${mark(accent, scale)}
</svg>`;

const browser = await chromium.launch();
const page = await browser.newPage();
async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  const src = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  await page.setContent(
    `<style>body{margin:0}img{display:block}</style><img src="${src}" width="${size}" height="${size}">`,
  );
  return page.screenshot({ omitBackground: true });
}

/** An ICO whose frames are PNGs, which every current browser reads. */
function ico(frames) {
  const header = Buffer.alloc(6 + 16 * frames.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  frames.forEach(({ size, data }, index) => {
    const entry = 6 + 16 * index;
    header.writeUInt8(size % 256, entry);
    header.writeUInt8(size % 256, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...frames.map(({ data }) => data)]);
}

try {
  const write = (file, data) => {
    writeFileSync(file, data);
    console.log(`icons: ${file}`);
  };
  // Browsers that read the SVG only show it in tabs, so it carries the small master.
  write('public/favicon.svg', tile(true));
  const frames = [];
  for (const size of [16, 32, 48]) frames.push({ size, data: await png(tile(size <= 32), size) });
  write('public/favicon.ico', ico(frames));
  write('public/apple-touch-icon.png', await png(fullBleed(0.9), 180));
  write('public/icon-192.png', await png(tile(), 192));
  write('public/icon-512.png', await png(tile(), 512));
  // Maskable icons are cropped to a circle as small as 80% of the side; the mark stays inside it.
  write('public/icon-maskable-512.png', await png(fullBleed(0.74), 512));
  const manifest = {
    name: 'Shawn Kawabe',
    short_name: 'Shawn Kawabe',
    start_url: '/',
    display: 'browser',
    background_color: surface,
    theme_color: surface,
    icons: [
      { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
      { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
      { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  };
  write('public/site.webmanifest', `${JSON.stringify(manifest, null, 2)}\n`);
  // No tile, in currentColor, so it takes the colour of whatever holds it (header lockup).
  write(
    'src/assets/logo-mark.svg',
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="6 9 20.5 14" fill="none" aria-hidden="true">${mark('currentColor')}</svg>\n`,
  );
} finally {
  await browser.close();
}
